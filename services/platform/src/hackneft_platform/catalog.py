def _code(prefix: str, tag: str) -> str:
    """Код датчика так, как его формирует агрегатор: приставка источника и тег в нижнем
    регистре (services/aggregator, source.py)."""
    return prefix + tag.lower()


# Описательные имена всех рядов агрегатора. Название источника входит в имя, потому что
# описания тегов разных источников могут совпадать, а имя в справочнике указывает ровно
# на один код.
_TITLES: dict[str, str] = {}
_TITLES |= {_code("avt_", tag): f"АВТ. {title}" for tag, title in AVT_TAGS.items()}
_TITLES |= {_code("ht_", tag): f"24-2000. {title}" for tag, title in HT_TAGS.items()}
_TITLES |= {_code("pack_", tag): f"ПАК. {title}" for tag, title in PAK_TAGS.items()}
_TITLES |= {
    _code("lims_", f"{point}.{indicator}"):
        f"ЛИМС. {LIMS_POINTS[point]}. {LIMS_INDICATORS[indicator]}"
    for point, indicators in LIMS_TAGS.items()
    for indicator in indicators
}

# Исходные имена тегов ПАК и ЛИМС (как в длинном CSV) — тоже синонимы: по ним ряды ищут
# в документации и в выгрузках.
_SOURCE_TAGS: dict[str, str] = {_code("pack_", tag): tag for tag in PAK_TAGS}
_SOURCE_TAGS |= {
    _code("lims_", f"{point}.{indicator}"): f"{point}.{indicator}"
    for point, indicators in LIMS_TAGS.items()
    for indicator in indicators
}

