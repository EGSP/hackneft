"""Исходный перечень кодов датчиков и их зарегистрированные синонимы.

Раньше жил как `KNOWN_SENSOR_TAGS` в удалённом observers.py и нигде не использовался.
Его место — таблица `sensor_names`: при инициализации БД (db.py:_seed_sensor_names)
каждый код записывается туда как имя самого себя (sensor_code == name), а затем
добавляются синонимы из `SENSOR_SYNONYMS`.
"""

KNOWN_SENSOR_CODES = {
    "F1", "F2", "P3", "W4", "T5", "T6", "W7", "P8", "F9", "W10",
    "T11", "T12", "P13", "F14", "F15", "T16", "F17", "T18", "F19",
    "Q20", "Q21", "F22", "T23", "P24", "F25", "F26",
    # Лабораторное определение серы в продукте гидроочистки (ЛИМС, точка отбора 2,
    # показатель Mg.Sulfur). В перечне тегов АСУ ТП такого кода нет: измерение приходит
    # не с датчика, а из лабораторной системы. Код заведён здесь по образцу поточного
    # Q21, чтобы оба ряда серы хранились в одной таблице измерений и сравнивались
    # одним запросом.
    "L21",
}

# Синонимы кодов датчиков. Ключ — код, значение — имена, под которыми тот же датчик
# известен в других системах и в интерфейсе. Все они попадают в sensor_names наравне
# с самим кодом, поэтому запрос по любому из них возвращает одни и те же измерения
# (см. представление sensor_query в models.py).
#
# Заполнен пока только для двух рядов серы в продукте гидроочистки — их показывает
# главная страница интерфейса. Остальные коды остаются именами самих себя.
SENSOR_SYNONYMS = {
    "Q21": ("ПАК", "Сера ПАК", "24-2000:Mg.Sulfur"),
    "L21": ("ЛИМС", "Сера ЛИМС", "Гидроочистка.Точка отбора 2.Mg.Sulfur"),
}

# Имена двух рядов серы в продукте, по которым их запрашивает главная страница, и норма
# по ГОСТ, общая для обоих: 10 мг/кг. Единицы поточного анализатора (ppm) и лаборатории
# (мг/кг) обозначают одну и ту же величину, поэтому ряды сравнимы напрямую и наносятся
# на один график.
#
# Здесь объявлены именно имена из справочника sensor_names, а не коды датчиков. К какому
# коду привязано имя — вопрос содержимого справочника: при смене источника данных (другой
# код того же измерения, приставка установки в коде и тому подобное) правится строка
# справочника, а платформа и интерфейс остаются прежними. Сами эти имена заведены выше
# как синонимы кодов Q21 и L21.
SULFUR_PAK_NAME = "ПАК"
SULFUR_LIMS_NAME = "ЛИМС"
SULFUR_LIMIT_MG_KG = 10.0

# Имена, от которых зависит главная страница. Удалять их из справочника нельзя: без такой
# строки имя не разрешается в код датчика и ряд на графике исчезает (см. api.py).
SULFUR_NAMES = (SULFUR_PAK_NAME, SULFUR_LIMS_NAME)
