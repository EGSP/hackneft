"""Описание источников телеметрии.

Сведения взяты из `docs/Спецификация данных.md`: состав пакета (раздел 1), совпадение имён
тегов у двух установок (раздел 2), служебный код отсутствия данных (раздел 3) и перечень
непригодных тегов (раздел 4).
"""

from dataclasses import dataclass

MISSING_VALUE_CODE = 307.0
"""Служебный код отсутствия данных. Встречается в 64 из 71 столбца выгрузки АВТ и в 15 из 26
столбцов выгрузки 24-2000. Это не измерение, поэтому такие значения не отправляются."""


@dataclass(frozen=True, slots=True)
class SourceSpec:
    """Описание одного файла телеметрии."""

    key: str
    """Краткое обозначение установки. Входит в идентификаторы веб-интерфейса."""
    title: str
    file_name: str
    prefix: str
    """Приставка к коду датчика. Шестнадцать имён тегов совпадают у двух установок и означают
    разные величины, поэтому код без указания установки неоднозначен."""
    origin: str
    """Значение поля `source` в записи платформы: откуда пришло показание."""
    excluded: frozenset[str]
    """Столбцы файла, не содержащие осмысленных значений на всём периоде выгрузки."""


SOURCES: tuple[SourceSpec, ...] = (
    SourceSpec(
        key="avt",
        title="АВТ",
        file_name="avt_tags.csv",
        prefix="avt_",
        origin="scada",
        # D10 — 99,99 % записей равны коду 307, остальные равны постоянному значению 240.
        # F26 и F5 — почти все оставшиеся записи отрицательны при отрицательной медиане.
        # P52 — перепад давления практически не разрешается прибором: медиана и процентили нулевые.
        excluded=frozenset({"D10", "F26", "F5", "P52"}),
    ),
    SourceSpec(
        key="ht",
        title="24-2000",
        file_name="242000_tags.csv",
        prefix="ht_",
        origin="scada",
        # Непригодных столбцов в этой выгрузке не выявлено.
        excluded=frozenset(),
    ),
)

