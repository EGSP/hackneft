from dataclasses import dataclass
from typing import Literal

MISSING_VALUE_CODE = 307.0
"""Служебный код отсутствия данных. Встречается в 64 из 71 столбца выгрузки АВТ и в 15 из 26
столбцов выгрузки 24-2000. Это не измерение, поэтому такие значения не отправляются."""

Layout = Literal["wide", "long"]
"""Формат CSV: широкий (столбец на тег) или длинный (`date,tag,value`)."""


@dataclass(frozen=True, slots=True)
class SourceSpec:
    """Описание одного файла источника."""

    key: str
    """Краткое обозначение источника. Входит в идентификаторы веб-интерфейса."""
    title: str
    file_name: str
    prefix: str
    """Приставка к коду датчика. Делает код однозначным между установками и видами данных."""
    origin: str
    """Значение поля `source` в записи платформы: откуда пришло показание."""
    layout: Layout
    """Формат файла. Телеметрия — широкая таблица; ЛИМС и ПАК — длинный CSV после конвертации."""
    excluded: frozenset[str] = frozenset()
    """Столбцы файла (широкий формат), не содержащие осмысленных значений на всём периоде."""


