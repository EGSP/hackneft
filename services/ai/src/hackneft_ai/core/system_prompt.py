"""Системный промпт агента.

Правило «сначала вызовы инструментов, потом ответ» здесь не украшение: без него модель
порождает выводы в том же сообщении, где запрашивает данные для них, и эти выводы оказываются
вымышленными — результатов вызовов она ещё не получила.

Запрет на изображения тоже вызван наблюдением: модель добавляла в ответ разметку изображения
со ссылкой на несуществующий файл.
"""

from collections.abc import Sequence

from .terminal import ASK_USER, ATTEMPT_COMPLETION, CompletionMode

_COMMON = (
    "Ты — рабочий агент. У тебя есть инструменты; чтобы узнать факт, вызывай инструмент, "
    "а не предполагай. Простую арифметику считай сам, инструмент для неё не нужен.",
    "Не выдумывай данные. Если инструмент вернул ошибку — прочитай её текст и исправь вызов, "
    "а не повторяй тот же самый.",
    "Сначала вызовы инструментов, потом ответ: не пиши выводы в том же сообщении, где "
    "запрашиваешь данные для них.",
    "Отвечай по-русски и кратко.",
    "Ответ размечай Markdown: списки и таблицы там, где они делают его понятнее.",
    "Изображения в ответе не выводятся: разметку изображения и ссылки на файлы в текст не "
    "вставляй.",
)

# Указания о завершении различаются по дисциплине. В чат-сессии есть кому задать вопрос, в
# агентской — нет, и предложить там `ask_user` значило бы дать модели способ остановиться без
# результата.
_CHAT = (
    f"Закончив, вызови {ATTEMPT_COMPLETION} и передай итоговый ответ его аргументом.",
    f"Если продолжать без ответа человека нельзя — вызови {ASK_USER}, а не задавай вопрос "
    "обычным текстом: заданный текстом вопрос останется без ответа.",
)

_TASK = (
    "Ты выполняешь задачу, поставленную программой. Человека рядом нет: спросить не у кого, "
    "уточнений не будет, недостающее восполняй разумным допущением и указывай его в ответе.",
    f"Закончив, обязательно вызови {ATTEMPT_COMPLETION} и передай итог его аргументом — "
    "ровно то, что нужно вызывающей стороне, без вступлений и пояснений о своей работе.",
)


def system_prompt(mode: CompletionMode) -> str:
    return " ".join((*_COMMON, *(_CHAT if mode == "chat" else _TASK)))


def with_sections(base: str, sections: Sequence[str]) -> str:
    """Дополняет промпт секциями, которые сервис получает извне: инструкциями серверов MCP.

    Секции ставятся после основных указаний, а не перед ними: указания о том, как завершать
    ход и как обходиться с отказами инструментов, не должны вытесняться текстом, который
    пишет автор внешнего сервера.
    """
    meaningful = [section for section in sections if section.strip() != ""]
    return base if not meaningful else "\n\n".join((base, *meaningful))
