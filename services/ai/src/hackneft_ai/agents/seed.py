async def seed_defaults(agents: AgentDirectory, instructions: InstructionDirectory) -> None:
    """Заполняет пустые справочники. Карточка по умолчанию получает только те инструкции,
    которые есть в справочнике: инструкции могли быть заведены вручную до первого запуска с
    карточками."""
    if not await instructions.list_instructions():
        for instruction in INSTRUCTIONS:
            await instructions.create(instruction)
        logger.info("справочник инструкций заполнен по умолчанию: %d", len(INSTRUCTIONS))

    if not await agents.is_empty():
        return
    known = {item.id for item in await instructions.list_instructions()}
    for agent in AGENTS:
        attached = [item for item in agent.instructions if item in known]
        await agents.create(agent.model_copy(update={"instructions": attached}))
    logger.info("справочник агентов заполнен по умолчанию: %d", len(AGENTS))
