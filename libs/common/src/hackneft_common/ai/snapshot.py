"""Снимок постоянной части запроса к модели.

Постоянная часть — всё, что уходит в запрос помимо переписки: указания сервиса, секции,
дописанные к ним, и описания инструментов. Переписка восстанавливается из журнала, а
постоянная часть в журнал не пишется: описания инструментов занимают десятки килобайт и
повторялись бы на каждом шаге. Она хранится отдельно, одной записью на каждое различающееся
содержимое, а событие начала шага ссылается на свой снимок.
"""

from pydantic import JsonValue

from .base import ApiModel
from .tools import ToolSource


class SnapshotTool(ApiModel):
    """Инструмент в том виде, в каком его описание ушло модели, с отметкой происхождения."""

    name: str
    description: str
    parameters: dict[str, JsonValue]
    source: ToolSource


class RequestSnapshotContent(ApiModel):
    prompt: str
    """Указания сервиса."""
    sections: list[str]
    """Секции, дописанные к указаниям: текстовые инструкции серверов MCP."""
    tools: list[SnapshotTool]
    """Инструменты в том порядке, в каком ушли модели, включая терминальные."""


class RequestSnapshot(RequestSnapshotContent):
    id: str
    """Хеш содержимого: одинаковое содержимое получает один идентификатор."""
    created_at: str
