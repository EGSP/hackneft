"""Сессия ИИ-сервиса."""

from typing import Literal

from pydantic import Field, JsonValue

from .base import ApiModel

SessionKind = Literal["chat", "agent"]
"""Вид сессии.

Виды различаются тем, кто подаёт вход и что считается завершением; журнал, поток событий
и прерывание у них общие.

`chat` — вход от человека или платформы сообщениями, ходов неограниченно, завершения не
наступает. `agent` — вход одной постановкой задачи, завершение по вызову терминального
инструмента; участия человека не требует.
"""

SessionStatus = Literal["idle", "running", "completed", "failed"]
"""Состояние сессии. `running` означает, что ход идёт прямо сейчас.

Терминальные состояния `completed` и `failed` достижимы только для вида `agent`: чат-сессия
завершения не имеет и остаётся в `idle` между ходами.
"""


class Session(ApiModel):
    id: str
    title: str
    kind: SessionKind
    status: SessionStatus
    created_at: str
    updated_at: str
    event_count: int
    """Число событий в журнале: по нему клиент понимает, есть ли что догружать."""
    model_id: str | None
    """Запись справочника моделей, закреплённая за сессией.

    Пусто в двух случаях: модель ещё не назначалась — чат создан при пустом справочнике и
    получит модель по умолчанию первым ходом, — либо запись удалена, и тогда ход
    отклоняется, пока не выбрана другая модель.
    """
    model_name: str | None
    """Идентификатор назначенной модели. Сохраняется и после удаления записи справочника."""
    model_provider: str | None
    """Провайдер назначенной модели. Сохраняется вместе с идентификатором."""
    parent_id: str | None
    """Порождающая сессия. Пусто у корневых."""
    agent_id: str | None = None
    """Карточка агента, по которой создана сессия. Пусто, если сессия создана без карточки
    либо карточка удалена; системный промпт карточки сессия хранит у себя."""
    result: JsonValue = None
    """Итог завершённой агентской сессии: итоговый ответ текстом либо объект по схеме
    итога, если она задана при создании."""
    input: JsonValue = None
    """Исходные данные, переданные при создании агентской сессии."""
    failure_message: str | None


class RenameSessionRequest(ApiModel):
    title: str = Field(min_length=1, max_length=200)
